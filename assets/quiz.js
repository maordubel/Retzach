  function score(mode, answers) {
    const want = {};
    answers.forEach(a => Object.entries(a.w || {}).forEach(([t, v]) => { want[t] = (want[t] || 0) + v; }));
    const maxPos = Object.values(want).reduce((s, v) => s + Math.max(0, v), 0) || 1;

    const list = profiles();
    const out = list.map(p => {
      let s = 0; const hit = [];
      Object.entries(want).forEach(([t, v]) => {
        if (p.tags.has(t)) { s += v; if (v > 0) hit.push(t); }
        else if (v < 0) s -= v * 0.35;
      });
      /* נרמול לפי עושר התגיות — כדי שתיק עם טקסט ארוך לא ינצח בכל פעם
         רק בגלל שיש לו יותר מילים */
      s = s / Math.sqrt(Math.max(4, p.tags.size)) * 3.1;
      /* רעש קטן ויציב לפי מזהה — שני אנשים עם אותן תשובות בדיוק לא תמיד יקבלו אותו דבר */
      s += ((p.id.charCodeAt(0) * 7 + p.id.length * 13) % 11) * 0.06;
      return { p, s, hit, pct: Math.max(41, Math.min(97, Math.round((s / maxPos) * 190))) };
    }).sort((a, b) => b.s - a.s);

    return out;
  }

